import { describe, expect, it } from "vitest";
import defaults from "@/lib/studio/generation/studio-llm.defaults.json";

// 2026-09-09 실사용에서 글 구조 초안 생성이 약 75초 만에 끊겼다.
//
// 원인은 우리 서버가 스스로에게 준 시간이 **우리 앞의 프록시가 허용하는 시간보다 길다**는
// 것이었다. 한 번 시도에 90초를 주고 최대 두 번 시도하니 서버 예산은 최대 180초인데,
// 프록시는 100초쯤에서 연결을 끊는다. 그래서 첫 시도가 느리면 사용자는 **어떤 경우에도**
// 결과를 볼 수 없다. 만들어지긴 하는데 화면에는 영영 닿지 않는다. 비용만 나간다.
//
// 서버가 자기 예산을 프록시 창보다 크게 잡는 순간 그 초과분은 전부 사용자에게 실패로
// 보인다. 그래서 예산을 창 안에 가둔다. 첫 시도가 느리면 빨리 포기하고, 훨씬 빠른 보조
// 모델이 창 안에서 답을 낸다.
// ★2026-09-10 정정: 72초·75초 실패를 프록시 절단으로 읽고 창을 70초로 잡았다. **틀렸다.**
// 그 실패들의 진짜 원인은 결과 잘림과 줄표 계약 위반이었고, 고친 뒤 카드뉴스 생성이
// **121초에 성공**했다. 즉 창은 70초보다 훨씬 넓다.
//
// 두 번 다 같은 실수를 했다. 실패 시각이 비슷하다는 것만 보고 원인을 시간으로 단정했다.
// 시간이 원인이라면 시간을 줄였을 때 결과가 달라져야 하는데 달라지지 않았다. 그때 가설을
// 버렸어야 했다.
//
// 창을 실측 성공 사례(121초)보다 넉넉히 잡되, 무한정 두지는 않는다. 사용자가 하염없이
// 기다리는 것도 실패다. 150초를 상한으로 삼는다.
const PROXY_WINDOW_MS = 150_000; // 실측: 121초 생성이 성공(2026-09-10)
const RESERVE_MS = 20_000; // 프롬프트 조립·DB·네트워크 몫

describe("생성 예산은 프록시 창 안에 있어야 한다", () => {
  it("최악의 경우 총 시간이 프록시 창을 넘지 않는다", () => {
    const worstCase = defaults.max_attempts * defaults.timeout_ms;
    expect(worstCase + RESERVE_MS).toBeLessThanOrEqual(PROXY_WINDOW_MS);
  });

  // 시도를 나눠 갖는 것보다 한 번에 충분히 주는 편이 낫다. 창이 70초뿐이라 두 번으로 쪼개면
  // 어느 쪽도 무거운 작업(영상)을 끝낼 만큼 받지 못하고, 결국 두 번 다 실패하며 시간만 쓴다.
  it("한 번 시도가 창 안에서 실질적인 시간을 받는다", () => {
    // 카드뉴스처럼 무거운 형식은 2분 넘게 걸린다. 넉넉히 주지 않으면 그 형식만 못 만든다.
    expect(defaults.timeout_ms).toBeGreaterThanOrEqual(90_000);
    expect(defaults.timeout_ms).toBeLessThanOrEqual(PROXY_WINDOW_MS - RESERVE_MS);
  });
});
